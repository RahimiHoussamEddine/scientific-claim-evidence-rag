"""Streamlit interface for local evidence retrieval and claim verification."""

from __future__ import annotations

import streamlit as st

from scientific_evidence_rag.data import load_claims
from scientific_evidence_rag.paths import PROCESSED_DIR, REPORTS_DIR
from scientific_evidence_rag.pipeline import EvidenceAssistant, load_cached_metrics


@st.cache_resource(show_spinner="Loading the local scientific abstract index…")
def load_assistant() -> EvidenceAssistant:
    return EvidenceAssistant.from_processed_data()


def main() -> None:
    st.set_page_config(page_title="Scientific Evidence Assistant", page_icon="🔬", layout="wide")
    st.title("Scientific Claim Evidence Assistant")
    st.caption(
        "A local RAG demonstration over the SciFact abstract corpus. "
        "It surfaces benchmark evidence; it is not a systematic review or medical advice."
    )
    if not (PROCESSED_DIR / "corpus.jsonl").is_file():
        st.warning("SciFact data is not prepared. From this project directory, run `make fetch`.")
        st.stop()

    with st.sidebar:
        st.header("Search settings")
        method = st.selectbox("Retrieval method", ["hybrid", "bm25", "dense"], index=0)
        k = st.slider("Abstracts to retrieve", min_value=1, max_value=10, value=5)
        st.markdown("The dense and hybrid methods use a pinned local sentence embedding model.")
        st.markdown("Generation uses the pinned FLAN-T5-small weights on CPU.")

    try:
        assistant = load_assistant()
    except Exception as error:
        st.error(f"Could not load the local index: {error}")
        st.stop()

    metrics = load_cached_metrics(REPORTS_DIR / "validation_metrics.json")
    sample_claims = []
    dev_path = PROCESSED_DIR / "claims_dev.jsonl"
    if dev_path.exists():
        sample_claims = load_claims(dev_path)
    sample_by_id = {claim.claim_id: claim for claim in sample_claims}
    choices = ["Write a claim"] + [
        f"SciFact dev #{claim.claim_id}: {claim.text[:110]}" for claim in sample_claims[:80]
    ]
    selected = st.selectbox("Start from an example or write your own", choices)
    default_text = ""
    if selected != "Write a claim":
        selected_id = int(selected.split("#", 1)[1].split(":", 1)[0])
        default_text = sample_by_id[selected_id].text
    claim_text = st.text_area(
        "Scientific claim",
        value=default_text,
        placeholder="Enter one specific, verifiable scientific claim…",
        height=100,
    )
    run = st.button(
        "Retrieve evidence and verify locally", type="primary", disabled=not claim_text.strip()
    )

    if run:
        with st.spinner("Searching the corpus and running the local model…"):
            try:
                result = assistant.verify(claim_text.strip(), method=method, k=k)
            except Exception as error:
                st.error(f"Local verification could not run: {error}")
                st.stop()
        left, right = st.columns([1, 2])
        with left:
            verdict = result["verdict"] or "Unparsed model response"
            st.metric("Model verdict", verdict.replace("_", " "))
            st.caption("Generated by FLAN-T5-small from up to the first three retrieved abstracts.")
            st.write(result["answer"] or "The local model returned an empty response.")
        with right:
            st.subheader("Retrieved abstracts")
            st.caption(
                "Abstracts are displayed locally from the licensed benchmark; "
                "they are not bundled with the repository."
            )
            for item in result["evidence"]:
                with st.expander(f"[{item['doc_id']}] {item['title']}", expanded=False):
                    for sentence in item["abstract"]:
                        st.write(sentence)
                    st.caption(f"Retrieval scores: {item['scores']}")
        if metrics and metrics.get("generation"):
            verdict_metrics = metrics["generation"]["verdict_metrics"]
            st.warning(
                "The local verdict is experimental. On the labeled SciFact dev split, "
                f"macro-F1 was {verdict_metrics['macro_f1']:.3f} and "
                f"{verdict_metrics['unparseable_fraction']:.1%} of outputs could not be parsed. "
                "Review the retrieved abstracts directly; do not rely on the generated label."
            )
        else:
            st.warning(
                "The local verdict is experimental. Review the retrieved abstracts directly; "
                "do not rely on the generated label."
            )

    st.divider()
    st.subheader("Benchmark evidence")
    if metrics is None:
        st.info("Run `make evaluate` after `make build` to create aggregate retrieval metrics.")
    else:
        st.caption(
            "Official SciFact dev split only. The unlabeled hidden test split is not scored here."
        )
        retrieval = metrics.get("retrieval", {})
        columns = st.columns(3)
        for column, name in zip(columns, ("bm25", "dense", "hybrid"), strict=False):
            values = retrieval.get(name, {})
            column.markdown(f"**{name.upper()}**")
            column.metric("Evidence Recall@5", f"{values.get('evidence_recall_at_5', 0):.3f}")
            column.metric("Evidence nDCG@5", f"{values.get('evidence_ndcg_at_5', 0):.3f}")
        if metrics.get("generation"):
            st.metric(
                "FLAN-T5 verdict macro-F1",
                f"{metrics['generation']['verdict_metrics']['macro_f1']:.3f}",
            )
            st.caption(metrics["generation"]["citation_metric_note"])


if __name__ == "__main__":
    main()
